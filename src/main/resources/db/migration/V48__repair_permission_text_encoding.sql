        WHEN 'ROLE_PERMISSION_READ_BINDINGS' THEN '角色管理'
        WHEN 'ROLE_READ' THEN '角色管理'
        WHEN 'ROLE_STATUS' THEN '角色管理'
        WHEN 'ROLE_UPDATE' THEN '角色管理'
